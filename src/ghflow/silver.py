"""The dbt silver layer, generated from `ghflow.fields` so a field's era is declared once. Pure.

One view per known event type (plus one for types the contract does not know yet), each with an
enforced dbt contract: exactly these columns, these types. Every payload field with an era gets
a test named after the field and the era, which fails if a value appears outside it.

    python -m ghflow.commands.silver generate   # writes dbt/ghflow/models/silver/ and one test
    python -m ghflow.commands.silver check      # exit 1 if the committed files differ
"""

from __future__ import annotations

import re
from datetime import datetime

from ghflow.fields import ENVELOPE_COLUMNS, FIELDS, KNOWN_TYPES, Field

HEADER = "generated by ghflow.silver (python -m ghflow.commands.silver generate); do not edit"
STAGING = "stg_gharchive__events"
UNKNOWN = "silver_unknown_events"

_KIND_SQL = {"int": "bigint", "str": "varchar", "bool": "boolean", "count": "bigint"}
_ENVELOPE_SQL = {
    "id": "bigint",
    "type": "varchar",
    "created_at": "timestamp with time zone",
    "actor_id": "bigint",
    "actor_login": "varchar",
    "repo_id": "bigint",
    "repo_name": "varchar",
    "org_id": "bigint",
    "org_login": "varchar",
    "public": "boolean",
}
_PARTITION_SQL = {"event_date": "date", "event_hour": "integer"}


def model_name(event_type: str) -> str:
    """`PullRequestReviewEvent` -> `silver_pull_request_review_events`."""
    words = re.sub(r"(?<!^)(?=[A-Z])", "_", event_type.removesuffix("Event")).lower()
    return f"silver_{words}_events"


def fields_of(event_type: str) -> list[Field]:
    """The payload fields this type carries, first declaration per column name, in FIELDS order."""
    seen: dict[str, Field] = {}
    for f in FIELDS:
        if event_type in f.types:
            seen.setdefault(f.name, f)
    return list(seen.values())


def _era_bound(at: datetime | None) -> str:
    return "null" if at is None else f'"{at:%Y-%m-%d %H:%M:%S}+00"'


def _era_slug(f: Field) -> str:
    parts = []
    if f.from_:
        parts.append(f"from_{f.from_:%Y_%m_%dT%H}")
    if f.until:
        parts.append(f"until_{f.until:%Y_%m_%dT%H}")
    return "__".join(parts)


def model_sql(event_type: str | None) -> str:
    """A typed view: envelope + this type's payload columns + the partition columns."""
    payload = [f.name for f in fields_of(event_type)] if event_type else []
    columns = list(ENVELOPE_COLUMNS) + payload + list(_PARTITION_SQL)
    if event_type:
        where = f"type = '{event_type}'"
    else:
        known = ", ".join(f"'{t}'" for t in sorted(KNOWN_TYPES))
        where = f"type is null or type not in ({known})"
    select = ",\n    ".join(columns)
    return (
        f"-- {HEADER}\n"
        "{{ config(materialized='view') }}\n\n"
        f"select\n    {select}\nfrom {{{{ ref('{STAGING}') }}}}\nwhere {where}\n"
    )


def _column_yaml(name: str, data_type: str, tests: list[str]) -> list[str]:
    lines = [f"      - name: {name}", f"        data_type: {data_type}"]
    if tests:
        lines.append("        data_tests:")
        lines += tests
    return lines


def _era_test(model: str, f: Field) -> list[str]:
    return [
        "          - in_era:",
        f"              name: era__{model}__{f.name}__{_era_slug(f)}",
        "              arguments:",
        f"                from_: {_era_bound(f.from_)}",
        f"                until: {_era_bound(f.until)}",
    ]


def _model_yaml(event_type: str | None) -> list[str]:
    model = model_name(event_type) if event_type else UNKNOWN
    described = (
        f"`{event_type}` events" if event_type else "events of a type the contract does not know"
    )
    lines = [
        f"  - name: {model}",
        f'    description: "Silver {described}: the envelope, their typed payload fields and the hour."',
        "    config:",
        "      contract:",
        "        enforced: true",
        "    columns:",
    ]
    for name in ENVELOPE_COLUMNS:
        tests = ["          - not_null"] if name in {"id", "created_at"} else []
        lines += _column_yaml(name, _ENVELOPE_SQL[name], tests)
    for f in fields_of(event_type) if event_type else []:
        tests = _era_test(model, f) if (f.from_ or f.until) else []
        lines += _column_yaml(f.name, _KIND_SQL[f.kind], tests)
    for name, data_type in _PARTITION_SQL.items():
        lines += _column_yaml(name, data_type, ["          - not_null"])
    return lines


def schema_yaml() -> str:
    lines = [f"# {HEADER}", "version: 2", "", "models:"]
    for event_type in sorted(KNOWN_TYPES):
        lines += _model_yaml(event_type)
    lines += _model_yaml(None)
    return "\n".join(lines) + "\n"


_ROWS_TEST = """\
-- {header}
-- Per hour, the silver views together hold exactly the bronze rows (M1-S3): every hour
-- where they differ is a failing row. Bronze is counted from the Parquet files themselves, up to
-- the newest hour staging loaded: an hour ingested while the build ran is the next run's work,
-- not a mismatch (M1-S5: two scheduled builds failed on exactly that race).
with loaded_until as (
    select max(event_date + to_hours(event_hour)) as newest from {{{{ ref('{staging}') }}}}
),
bronze as (
    select cast(date as date) as event_date, cast(hour as integer) as event_hour, count(*) as n
    from read_parquet('{{{{ var("bronze_events") }}}}', hive_partitioning = true)
    where cast(date as date) + to_hours(cast(hour as integer)) <= (select newest from loaded_until)
    group by all
),
silver as (
{union}
),
silver_by_hour as (
    select event_date, event_hour, sum(n) as n from silver group by all
)
select
    coalesce(b.event_date, s.event_date) as event_date,
    coalesce(b.event_hour, s.event_hour) as event_hour,
    b.n as bronze_rows,
    s.n as silver_rows
from bronze b
full outer join silver_by_hour s using (event_date, event_hour)
where b.n is distinct from s.n
"""


def rows_test_sql() -> str:
    """Per hour, the silver views together hold exactly the bronze rows; each differing hour fails."""
    models = [model_name(t) for t in sorted(KNOWN_TYPES)] + [UNKNOWN]
    selects = [
        f"    select event_date, event_hour, count(*) as n from {{{{ ref('{m}') }}}} group by all"
        for m in models
    ]
    return _ROWS_TEST.format(
        header=HEADER, staging=STAGING, union="\n    union all\n".join(selects)
    )


def files() -> dict[str, str]:
    """Every generated file, by path relative to dbt/ghflow/."""
    out = {f"models/silver/{model_name(t)}.sql": model_sql(t) for t in sorted(KNOWN_TYPES)}
    out[f"models/silver/{UNKNOWN}.sql"] = model_sql(None)
    out["models/silver/_silver.yml"] = schema_yaml()
    out["tests/silver_rows_equal_bronze_rows.sql"] = rows_test_sql()
    return out
