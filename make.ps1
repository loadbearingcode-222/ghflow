#!/usr/bin/env pwsh
# The project's single task runner. GNU Make is not installed on this Windows machine and the
# project path contains a space, so every command a story documents goes through here.
# Keep this file ASCII-only: Windows PowerShell 5.1 reads a BOM-less script as ANSI.
#
# Usage:  .\make.ps1 help
#         .\make.ps1 check

[CmdletBinding()]
param(
    [Parameter(Position = 0)]
    [string]$Target = 'help',
    # Only for `reset`: confirms that every named volume (all platform data) may be deleted.
    [switch]$Force,
    # Only for the backfill targets: the window's last hour, inclusive (e.g. 2026-10-05-11).
    [string]$To = '',
    # Only for replay / replay-verify: one GH Archive hour (e.g. 2026-08-03-0).
    [string]$Hour = ''
)

$ErrorActionPreference = 'Stop'
Set-Location -LiteralPath $PSScriptRoot

function Invoke-Checked {
    param([string]$Exe, [string[]]$Arguments)
    # Windows PowerShell 5.1 turns a native tool's stderr into error records whenever output
    # is redirected, and 'Stop' would abort on uv's progress lines. Judge by exit code only.
    $ErrorActionPreference = 'Continue'
    & $Exe @Arguments
    if ($LASTEXITCODE -ne 0) {
        throw "$Exe $($Arguments -join ' ') failed with exit code $LASTEXITCODE"
    }
}

# Verb-noun on purpose: a function named `uv` would shadow the executable (gotcha #9).
function Invoke-Uv { param([string[]]$Arguments) Invoke-Checked 'uv' $Arguments }
function Invoke-Compose { param([string[]]$Arguments) Invoke-Checked 'docker' (@('compose') + $Arguments) }

function New-Secret {
    param([int]$Length = 32)
    # Alphanumeric only, so a secret can sit inside a connection URL unescaped.
    $alphabet = [char[]]'ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnopqrstuvwxyz23456789'
    $bytes = New-Object byte[] $Length
    [System.Security.Cryptography.RandomNumberGenerator]::Create().GetBytes($bytes)
    return -join ($bytes | ForEach-Object { $alphabet[$_ % $alphabet.Length] })
}

function New-FernetKey {
    # A Fernet key is 32 random bytes, URL-safe base64 (what Airflow encrypts connections with).
    $bytes = New-Object byte[] 32
    [System.Security.Cryptography.RandomNumberGenerator]::Create().GetBytes($bytes)
    return [Convert]::ToBase64String($bytes).Replace('+', '-').Replace('/', '_')
}

function Invoke-Env {
    $values = @{
        'S3_ACCESS_KEY'          = ('ghflow' + (New-Secret 14))
        'S3_SECRET_KEY'          = (New-Secret 40)
        'PLATFORM_DB_PASSWORD'   = (New-Secret)
        'GHFLOW_OPS_PASSWORD'    = (New-Secret)
        'AIRFLOW_ADMIN_PASSWORD' = (New-Secret 16)
        'AIRFLOW_FERNET_KEY'     = (New-FernetKey)
        'AIRFLOW_JWT_SECRET'     = (New-Secret 48)
        'CLICKHOUSE_PASSWORD'    = (New-Secret)
    }
    $keys = @(Get-Content -LiteralPath '.env.example' | Where-Object { $_ -match '^([A-Z0-9_]+)=$' } | ForEach-Object { $_.TrimEnd('=') })
    $missing = @($keys | Where-Object { -not $values.ContainsKey($_) })
    if ($missing.Count -gt 0) { throw "make.ps1 env has no generator for: $($missing -join ', ')" }
    $path = Join-Path $PSScriptRoot '.env'
    if (Test-Path -LiteralPath $path) {
        # Never rewrite an existing secret (volumes were initialised with it); only add new keys.
        $present = @(Get-Content -LiteralPath $path | Where-Object { $_ -match '^([A-Z0-9_]+)=' } | ForEach-Object { ($_ -split '=', 2)[0] })
        $added = @($keys | Where-Object { $present -notcontains $_ })
        if ($added.Count -eq 0) { Write-Host '.env already complete - leaving it alone.'; return }
        $lines = $added | ForEach-Object { "$_=$($values[$_])" }
        Add-Content -LiteralPath $path -Value $lines -Encoding ascii
        Write-Host ".env: added $($added -join ', ')"
        return
    }
    $lines = @('# Generated by .\make.ps1 env. Never commit this file.') + ($keys | ForEach-Object { "$_=$($values[$_])" })
    Set-Content -LiteralPath $path -Value $lines -Encoding ascii
    Write-Host ".env written with $($keys.Count) generated values"
}

$Targets = [ordered]@{
    'hooks'            = 'Install git hooks (refuses direct pushes to main)'
    'sync'             = 'Create/refresh the local venv from uv.lock'
    'lint'             = 'Check formatting and lint rules'
    'format'           = 'Auto-fix formatting and lint rules'
    'typecheck'        = 'mypy --strict'
    'test'             = 'Unit tests'
    'layers'           = 'Import layers: the shell sits on the core, never the reverse (import-linter)'
    'check'            = 'sync + lint + typecheck + layers + test (what CI quality, import-layers and ratchet run)'
    'profile'          = 'Measure GH Archive (network), write the record, render docs/data/gharchive.md'
    'profile-render'   = 'Re-render docs/data/gharchive.md from the committed record (no network)'
    'contract-check'   = 'Apply the event contract to seven real hours (network) -> automation/runs/m0-s3/'
    'env'              = 'Write .env with generated secrets (never rewrites an existing one)'
    'doctor'           = 'Preflight: port holders, Docker RAM vs budget, path length (read-only)'
    'up'               = 'env + doctor + start the stack and wait until every service is healthy'
    'down'             = 'Stop and remove the containers (volumes are kept)'
    'ps'               = 'Show every service and its state'
    'logs'             = 'Follow the stack logs'
    'reset'            = 'down -v: delete every volume (needs -Force)'
    'backfill'         = 'Start the Airflow backfill of gharchive_ingest from 2026-08-03 (-To <last hour>)'
    'park'             = 'Pause the backfill; wait for in-flight hours; say whether it is safe to walk away'
    'resume'           = 'Unpause the backfill'
    'watch'            = 'Lander lag per partition; with -To <last hour>, backfill progress from the audit table'
    'backfill-verify'  = 'Every window hour has exactly one final verdict (-To <last hour>)'
    'replay'           = 'Publish one bronze hour to gharchive.events, checkpointed after the flush (-Hour)'
    'replay-verify'    = 'Read one hour back from the topic: events, duplicates, missing ids, markers (-Hour)'
    'dags'             = "Build the Airflow image's dag-test stage; run the DAG-integrity tests in it, network off"
    'test-integration' = 'Tests against the running stack (needs up)'
}

switch ($Target) {
    'help' {
        $width = ($Targets.Keys | Measure-Object -Property Length -Maximum).Maximum + 2
        Write-Host ''
        Write-Host '  ghflow targets' -ForegroundColor Cyan
        Write-Host ''
        foreach ($entry in $Targets.GetEnumerator()) { Write-Host ('  ' + $entry.Key.PadRight($width) + $entry.Value) }
        Write-Host ''
    }
    'hooks'     { Invoke-Checked 'git' @('config', 'core.hooksPath', '.githooks'); Write-Host 'git hooks installed from .githooks/' }
    'sync'      { Invoke-Uv @('sync', '--locked', '--group', 'dev', '--group', 'integration', '--group', 'dbt', '--group', 'stream', '--group', 'clickhouse') }
    'lint'      { Invoke-Uv @('run', 'ruff', 'check', '.'); Invoke-Uv @('run', 'ruff', 'format', '--check', '.') }
    'format'    { Invoke-Uv @('run', 'ruff', 'check', '--fix', '.'); Invoke-Uv @('run', 'ruff', 'format', '.') }
    'typecheck' { Invoke-Uv @('run', 'mypy') }
    'layers'    { Invoke-Uv @('run', 'lint-imports') }
    'test'      { Invoke-Uv @('run', 'pytest', 'tests/unit') }
    'profile'   { Invoke-Uv @('run', 'python', '-m', 'ghflow.commands.profile', 'measure') }
    'profile-render' { Invoke-Uv @('run', 'python', '-m', 'ghflow.commands.profile', 'render') }
    'contract-check' {
        # 2024 baseline, both sides of the trim, an outage hour, the broken-mix hour, a partial hour, a healthy hour
        $hours = @('2024-06-15-15', '2025-10-08-16', '2025-10-08-17', '2026-09-02-5', '2026-09-05-15', '2026-09-21-15', '2026-10-02-15')
        Invoke-Uv (@('run', 'python', '-m', 'ghflow.commands.contract') + $hours + @('--record', 'automation/runs/m0-s3/real_hours.json'))
    }
    'backfill'  { Invoke-Uv @('run', 'python', '-m', 'ghflow.commands.backfill', 'start', '--to', $To) }
    'park'      { Invoke-Uv @('run', 'python', '-m', 'ghflow.commands.backfill', 'park', '--wait') }
    'resume'    { Invoke-Uv @('run', 'python', '-m', 'ghflow.commands.backfill', 'resume') }
    'watch'     {
        if ($To) { Invoke-Uv @('run', 'python', '-m', 'ghflow.commands.backfill', 'watch', '--to', $To) }
        else { Invoke-Uv @('run', 'python', '-m', 'ghflow.commands.lander', 'lag') }
    }
    'backfill-verify' { Invoke-Uv @('run', 'python', '-m', 'ghflow.commands.backfill', 'verify', '--to', $To, '--out', 'automation/runs/m1-s2/verdicts.json') }
    'replay'    { Invoke-Compose @('run', '--rm', 'replayer', 'python', '-m', 'ghflow.commands.stream', 'replay', $Hour) }
    'replay-verify' { Invoke-Uv @('run', 'python', '-m', 'ghflow.commands.stream', 'verify', $Hour) }
    'env'       { Invoke-Env }
    'doctor'    { Invoke-Checked 'powershell' @('-NoProfile', '-ExecutionPolicy', 'Bypass', '-File', (Join-Path $PSScriptRoot 'scripts\doctor.ps1')) }
    'up'        {
        Invoke-Env
        & $PSCommandPath doctor
        Invoke-Compose @('up', '-d', '--build', '--wait')
        Write-Host ''
        Write-Host '  S3 API (SeaweedFS)  ->  http://127.0.0.1:39000   (S3_ACCESS_KEY / S3_SECRET_KEY in .env)' -ForegroundColor Green
        Write-Host '  SeaweedFS filer UI  ->  http://127.0.0.1:39001' -ForegroundColor Green
        Write-Host '  Postgres            ->  127.0.0.1:35432          (ghflow / GHFLOW_OPS_PASSWORD, db ghflow_ops)' -ForegroundColor Green
        Write-Host '  Airflow             ->  http://127.0.0.1:38082   (admin / AIRFLOW_ADMIN_PASSWORD in .env)' -ForegroundColor Green
        Write-Host ''
    }
    'down'      { Invoke-Compose @('down') }
    'ps'        { Invoke-Compose @('ps', '-a') }
    'logs'      { Invoke-Compose @('logs', '-f', '--tail=100') }
    'reset'     {
        if (-not $Force) { throw 'reset deletes every volume (all platform data). Re-run as: .\make.ps1 reset -Force' }
        Invoke-Compose @('down', '-v')
    }
    'dags'      {
        # docker build, not `compose build`: compose interpolates every ${VAR:?} first, so it
        # would refuse before .env exists. CI builds the same way.
        Invoke-Checked 'docker' @('build', '-f', 'docker/airflow/Dockerfile', '--target', 'dag-test', '-t', 'ghflow/airflow:dag-test', '.')
        $dags = Join-Path $PSScriptRoot 'airflow\dags'
        New-Item -ItemType Directory -Force -Path $dags | Out-Null
        # pytest is baked into the dag-test stage: the check runs with networking off (issue #14).
        Invoke-Checked 'docker' @('run', '--rm', '--network', 'none', '-e', 'AIRFLOW__CORE__LOAD_EXAMPLES=false',
            '-v', "${dags}:/opt/airflow/dags:ro", 'ghflow/airflow:dag-test',
            'python', '-m', 'pytest', '-q', '-p', 'no:cacheprovider', '/opt/ghflow/tests/dags')
    }
    'test-integration' { Invoke-Uv @('run', '--group', 'integration', 'pytest', '-m', 'integration', 'tests/integration') }
    'check'     {
        & $PSCommandPath sync
        & $PSCommandPath lint
        & $PSCommandPath typecheck
        & $PSCommandPath layers
        & $PSCommandPath test
        Write-Host 'check: lint, types, layers and unit tests all passed' -ForegroundColor Green
    }
    default {
        Write-Host "Unknown target '$Target'. Run .\make.ps1 help" -ForegroundColor Red
        exit 2
    }
}
